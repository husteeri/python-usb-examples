# protocol.py

PROTOCOL_VERSION = 1

SOF = bytes([0x55, 0xAA])

MAX_PAYLOAD_SIZE = 256


# Commands

CMD_PING = 0x01
CMD_GET_INFO = 0x02
CMD_GET_STATS = 0x03
CMD_RESET = 0x04

CMD_SET_CLOCK = 0x10
CMD_RESET_BUS = 0x11
CMD_SCAN = 0x12

CMD_I2C_WRITE = 0x20
CMD_I2C_READ = 0x21
CMD_I2C_WRITE_READ = 0x22


CMD_SPI_CONFIG    = 0x51
CMD_SPI_WRITE     = 0x52
CMD_SPI_READ      = 0x53
CMD_SPI_TRANSFER  = 0x54


CMD_SERIAL_CONFIG = 0x70
CMD_SERIAL_WRITE = 0x71
CMD_SERIAL_READ = 0x72
CMD_SERIAL_TRANSFER = 0x73



# Flags

FLAG_RESPONSE = 0x01
FLAG_EVENT = 0x02
FLAG_ERROR = 0x04



# Status

STATUS_OK = 0
STATUS_BUSY = 1
STATUS_CRC_ERROR = 2
STATUS_BAD_LENGTH = 3
STATUS_UNKNOWN_COMMAND = 4
STATUS_I2C_ERROR = 5
STATUS_I2C_TIMEOUT = 6
